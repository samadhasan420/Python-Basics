print("\n----- Text Modifier -----")

Text = "python is easy and python is powerful"

print("\nOriginal:", Text)
print("\nCapitalized:",Text.capitalize())
print("\nReplaced:",Text.replace("python","C#"))
print("\nFirst 'python' found at index:",Text.find("python"))
print("\n'python' count:",Text.count("python"))
print("\nEnds with 'powerful':",Text.endswith("powerful"))